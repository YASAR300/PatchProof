import { describe, it, expect } from "vitest";
import { parseRequirementsTxt } from "../worker/src/deps/requirements-parser.js";
import { parsePackageLock } from "../worker/src/deps/package-lock-parser.js";
import { parsePnpmLock } from "../worker/src/deps/pnpm-lock-parser.js";
import { parseYarnLock } from "../worker/src/deps/yarn-lock-parser.js";

describe("lockfiles — Dependency Manifest & Lockfile Parsers", () => {
  describe("requirements.txt parser", () => {
    it("parses pinned == requirements with inline comments and markers", () => {
      const content = `
# Core dependencies
flask==2.2.5
requests[security]==2.28.1 # pinned for security
pywin32==300; sys_platform == 'win32'
unpinned-pkg>=1.0.0
`;
      const result = parseRequirementsTxt(content);
      expect(result.dependencies.length).toBe(3);

      const flask = result.dependencies.find((d) => d.name.toLowerCase() === "flask");
      expect(flask).toBeDefined();
      expect(flask.installedVersion).toBe("2.2.5");
      expect(flask.ecosystem).toBe("PyPI");
      expect(flask.isDirect).toBe(true);

      const requests = result.dependencies.find((d) => d.name.toLowerCase() === "requests");
      expect(requests).toBeDefined();
      expect(requests.installedVersion).toBe("2.28.1");

      expect(result.unresolved.length).toBe(1);
      expect(result.unresolved[0].name).toBe("unpinned-pkg");
    });

    it("handles empty or comment-only requirements.txt", () => {
      expect(parseRequirementsTxt("").dependencies.length).toBe(0);
      expect(parseRequirementsTxt("# Just comments\n# nothing else").dependencies.length).toBe(0);
    });
  });

  describe("package-lock.json parser", () => {
    it("parses npm lockfile v2 / v3 packages", () => {
      const content = JSON.stringify({
        name: "test-app",
        version: "1.0.0",
        lockfileVersion: 3,
        packages: {
          "": {
            name: "test-app",
            version: "1.0.0",
            dependencies: {
              lodash: "^4.17.20",
            },
          },
          "node_modules/lodash": {
            version: "4.17.21",
            resolved: "https://registry.npmjs.org/lodash/-/lodash-4.17.21.tgz",
          },
          "node_modules/debug": {
            version: "4.3.4",
            resolved: "https://registry.npmjs.org/debug/-/debug-4.3.4.tgz",
          },
        },
      });

      const result = parsePackageLock(content);
      expect(result.dependencies.length).toBe(2);

      const lodash = result.dependencies.find((d) => d.name === "lodash");
      expect(lodash).toBeDefined();
      expect(lodash.installedVersion).toBe("4.17.21");
      expect(lodash.ecosystem).toBe("npm");
      expect(lodash.isDirect).toBe(true);

      const debug = result.dependencies.find((d) => d.name === "debug");
      expect(debug).toBeDefined();
      expect(debug.installedVersion).toBe("4.3.4");
      expect(debug.isDirect).toBe(false); // transitive
    });
  });

  describe("pnpm-lock.yaml parser", () => {
    it("parses pnpm lockfile format", () => {
      const content = `
lockfileVersion: '6.0'

dependencies:
  express:
    specifier: ^4.18.2
    version: 4.18.2

packages:
  /express@4.18.2:
    resolution: {integrity: sha512-5/psL6iVEkiGu9P8cQGHTcJRfZ3PYmr44MQFA3SWvCYMpZ92a9bCgbVGcq9PBL5f92v730c451k1g555Y555==}
  /cookie@0.5.0:
    resolution: {integrity: sha512-5/psL6iVEkiGu9==}
`;

      const result = parsePnpmLock(content);
      expect(result.dependencies.length).toBeGreaterThan(0);
      const express = result.dependencies.find((d) => d.name === "express");
      expect(express).toBeDefined();
      expect(express.installedVersion).toBe("4.18.2");
      expect(express.ecosystem).toBe("npm");
    });
  });

  describe("yarn.lock parser", () => {
    it("parses yarn.lock v1 format", () => {
      const content = `
# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

"axios@^1.4.0", "axios@^1.0.0":
  version "1.4.0"
  resolved "https://registry.yarnpkg.com/axios/-/axios-1.4.0.tgz"

ms@2.0.0:
  version "2.0.0"
  resolved "https://registry.yarnpkg.com/ms/-/ms-2.0.0.tgz"
`;

      const result = parseYarnLock(content);
      expect(result.dependencies.length).toBe(2);

      const axios = result.dependencies.find((d) => d.name === "axios");
      expect(axios).toBeDefined();
      expect(axios.installedVersion).toBe("1.4.0");
      expect(axios.ecosystem).toBe("npm");

      const ms = result.dependencies.find((d) => d.name === "ms");
      expect(ms).toBeDefined();
      expect(ms.installedVersion).toBe("2.0.0");
    });
  });
});
